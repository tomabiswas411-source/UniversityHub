export type UserRole = "super_admin" | "dept_admin" | "teacher" | "student";

export const DAYS_OF_WEEK = [
 "saturday",
 "sunday",
 "monday",
 "tuesday",
 "wednesday",
 "thursday",
] as const;
export type DayOfWeek = (typeof DAYS_OF_WEEK)[number];

