import { db } from "@/lib/db";
import { bdTodayISO, bdDaysAgoISO } from "@/lib/date-bd";

/**
 * Data-retention sweep — the platform's cost-effective auto-cleanup.
 *
 * The user's rule: unnecessary data should remove itself over time
 * (7 days – 1 month style windows) so the database stays small and the
 * Turso/Vercel bill stays low — WITHOUT hurting the platform.
 * Therefore everything that is a source of record is KEPT; only
 * ephemeral / superseded / expired noise is removed:
 *
 *  ── DELETED ──────────────────────────────────────────────────────
 *  • AttendanceSession  expired > 30 days   (Attendance rows are the
 *                                            permanent record; QR
 *                                            windows are ephemeral)
 *  • Notification       read   > 14 days
 *                       unread > 90 days   (user never saw it)
 *  • ScheduleChange     superseded/old > 180 days (notices + the
 *                                            attendance record keep
 *                                            the history)
 *  • Notice (auto-generated class-change spam) > 60 days
 *  • Notice             manually posted + expired > 30 days past expiry
 *  • AcademicCalendar   ended > 180 days
 *
 *  ── DEACTIVATED (kept, stops surfacing) ──────────────────────────
 *  • ScheduleChange     effectiveDate < today-45d → isActive=false
 *
 * Triggers:
 *  1. Vercel Cron daily (vercel.json → /api/maintenance/cleanup)
 *  2. Lazy: any authenticated /api/notifications GET after a 24h
 *     cold-start gap (fire-and-forget, zero user-visible cost).
 */

const DAY_MS = 24 * 60 * 60 * 1000;

// BD-calendar cutoffs — the old UTC-based slice filed "N days ago" under
// the wrong calendar day for the first 6 hours of each Bangladesh day.
const daysAgoISO = bdDaysAgoISO;
function daysAgoDate(days: number): Date {
  return new Date(Date.now() - days * DAY_MS);
}

export interface CleanupResult {
  attendanceSessions: number;
  notificationsRead: number;
  notificationsUnread: number;
  scheduleChangesDeleted: number;
  scheduleChangesDeactivated: number;
  autoNotices: number;
  expiredNotices: number;
  calendarEvents: number;
  ranAt: string;
}

/** Run the retention sweep once. Safe to call concurrently — every
    step is an independent idempotent deleteMany/deactivate. */
export async function runCleanup(): Promise<CleanupResult> {
  const today = bdTodayISO();

  const [
    attendanceSessions,
    notificationsRead,
    notificationsUnread,
    scheduleChangesDeleted,
    scheduleChangesDeactivated,
    autoNotices,
    expiredNotices,
    calendarEvents,
  ] = (
    await Promise.all([
    // QR windows older than a month — ephermal by design
    db.attendanceSession.deleteMany({
      where: { expiresAt: { lt: daysAgoDate(30) } },
    }),
    // Read notifications: 2 weeks is plenty of time to have seen them
    db.notification.deleteMany({
      where: { isRead: true, createdAt: { lt: daysAgoDate(14) } },
    }),
    // Unread: give a generous quarter before dropping something unseen
    db.notification.deleteMany({
      where: { isRead: false, createdAt: { lt: daysAgoDate(90) } },
    }),
    // Change records older than 6 months (their notices + attendance remain)
    db.scheduleChange.deleteMany({
      where: { effectiveDate: { lt: daysAgoISO(180) } },
    }),
    // Stop surfacing changes older than 45 days (kept, just inactive)
    db.scheduleChange.updateMany({
      where: { isActive: true, effectiveDate: { lt: daysAgoISO(45) } },
      data: { isActive: false },
    }),
    // Auto-generated class-change notices: noisy duplicates of the
    // change record — drop after 60 days
    db.notice.deleteMany({
      where: {
        isAutoGenerated: true,
        createdAt: { lt: daysAgoDate(60) },
      },
    }),
    // Manually posted notices that carry an expiry — remove 30 days
    // after that expiry. Notices WITHOUT expiry are kept (manual value).
    db.notice.deleteMany({
      where: {
        expiryDate: { not: null, lt: daysAgoDate(30) },
      },
    }),
    // Calendar events that ended over 6 months ago. Single-day events carry
    // no endDate — sweep those by their `date` too, or they live forever.
    db.academicCalendar.deleteMany({
      where: {
        OR: [
          { endDate: { lt: daysAgoDate(180) } },
          { AND: [{ endDate: null }, { date: { lt: daysAgoDate(180) } }] },
        ],
      },
    }),
    ])
  ).map((r) => r.count);

  return {
    attendanceSessions,
    notificationsRead,
    notificationsUnread,
    scheduleChangesDeleted,
    scheduleChangesDeactivated,
    autoNotices,
    expiredNotices,
    calendarEvents,
    ranAt: today,
  };
}

/* ---------------- lazy trigger (24h throttle) ---------------- */

const CLEANUP_INTERVAL_MS = 24 * 60 * 60 * 1000;
let lastCleanupAt = 0;
let inFlight: Promise<void> | null = null;

/**
 * Fire-and-forget sweep used by hot request paths. Runs at most once
 * per server process per 24h and never throws — caller does `void`.
 */
export function maybeRunCleanup(): void {
  const now = Date.now();
  if (now - lastCleanupAt < CLEANUP_INTERVAL_MS) return;
  if (inFlight) return;
  inFlight = runCleanup()
    .then((res) => {
      // Record the throttle timestamp ONLY on success — a failed sweep
      // must retry on the next request instead of going quiet for 24h.
      lastCleanupAt = Date.now();
      const total =
        res.attendanceSessions +
        res.notificationsRead +
        res.notificationsUnread +
        res.scheduleChangesDeleted +
        res.autoNotices +
        res.expiredNotices +
        res.calendarEvents;
      // One compact line — visibility without log spam
      console.log(
        `[cleanup] retention sweep: ${total} rows purged (sessions=${res.attendanceSessions} notif=${res.notificationsRead + res.notificationsUnread} changes=-${res.scheduleChangesDeleted}/deact=${res.scheduleChangesDeactivated} notices=${res.autoNotices + res.expiredNotices} cal=${res.calendarEvents})`
      );
    })
    .catch((err) => {
      console.error("[cleanup] retention sweep failed:", err);
    })
    .finally(() => {
      inFlight = null;
    });
}
